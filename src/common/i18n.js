const LANG_NAMES = { en: 'English', te: 'తెలుగు', hi: 'हिन्दी', mr: 'मराठी', kn: 'ಕನ್ನಡ', ta: 'தமிழ்', ml: 'മലയാളം' };

function setLang(lang) {
  I18N._lang = I18N[lang] ? lang : 'en';
  return I18N._lang;
}
function currentLang() {
  return I18N._lang || 'en';
}

/** Look up a key in the active language, falling back to English, then the key. */
function t(key, params) {
  const table = I18N[I18N._lang] || I18N.en;
  let s = table[key];
  if (s == null) s = I18N.en[key];
  if (s == null) return key;
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
  }
  return s;
}

/** "2 pilgrims" / "1 pilgrim" — English pluralises, Telugu/Hindi do not. */
function nPilgrims(count) {
  return count === 1 ? t('count.pilgrim.one') : t('count.pilgrim.many', { count });
}

