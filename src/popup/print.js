/**
 * Renders the booking summary handed over by the popup via chrome.storage.session
 * (memory only — the ID numbers never touch disk), then lets the user print or
 * save it as PDF. A trusted extension page, so it can read session storage.
 *
 * Built entirely with createElement + textContent — no innerHTML anywhere — so
 * the ID numbers are inserted as text, never parsed as markup.
 */
function el(tag, text, className) {
  const node = document.createElement(tag);
  if (text != null) node.textContent = String(text);
  if (className) node.className = className;
  return node;
}
function cell(tag, text) { return el(tag, text); }

async function main() {
  let data = null;
  try { data = (await api.storage.session.get('printData')).printData; } catch { /* no session */ }
  const root = document.getElementById('root');
  root.replaceChildren();
  if (!data || !Array.isArray(data.people)) {
    root.textContent = 'Nothing to print — open the checklist and try again.';
    return;
  }
  const c = data.contact || {};

  root.appendChild(el('h1', `${data.profileName} — booking summary`));

  const contactBits = [c.email, c.mobile, [c.city, c.state, c.pincode, c.country].filter(Boolean).join(', ')]
    .filter((x) => x && String(x).trim());
  root.appendChild(el('div', contactBits.join(' · '), 'contact'));

  const table = document.createElement('table');
  const thead = document.createElement('thead');
  const htr = document.createElement('tr');
  const heads = ['#', 'Name', 'Age', 'Gender', 'ID type', 'ID number'];
  if (data.anyExpiry) heads.push('Passport expiry');
  for (const h of heads) htr.appendChild(cell('th', h));
  thead.appendChild(htr);
  table.appendChild(thead);

  const tbody = document.createElement('tbody');
  data.people.forEach((p, i) => {
    const tr = document.createElement('tr');
    const vals = [i + 1, p.name, p.age, p.gender, p.idType, p.idNumber];
    if (data.anyExpiry) vals.push(p.passportExpiry);
    for (const v of vals) tr.appendChild(cell('td', v ?? ''));
    tbody.appendChild(tr);
  });
  table.appendChild(tbody);
  root.appendChild(table);

  root.appendChild(el('p',
    "Generated by Kolli's Tirumala Booking Helper for your own records. Contains ID numbers — keep it private. The booking itself is completed by you on TTD's website.",
    'foot'));

  document.title = `${data.profileName} — booking summary`;
  // Clear it from session once shown, so it does not linger.
  try { await api.storage.session.remove('printData'); } catch { /* */ }
}

document.getElementById('printBtn').addEventListener('click', () => window.print());
document.getElementById('closeBtn').addEventListener('click', () => window.close());
main();
